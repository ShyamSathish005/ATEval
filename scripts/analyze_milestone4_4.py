"""Analyze real M4.4 reviewer annotations without creating synthetic ratings."""

from __future__ import annotations

import json
import math
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ANNOTATIONS = ROOT / "experiments/milestone4_4/reviewer_annotations.jsonl"
OUTPUT = ROOT / "reports/milestone4_4"


def read_rows() -> list[dict]:
    if not ANNOTATIONS.exists():
        return []
    return [json.loads(line) for line in ANNOTATIONS.read_text(encoding="utf-8").splitlines() if line.strip()]


def bootstrap_proportion(values: list[bool], seed: int = 44, draws: int = 2000) -> dict:
    if not values:
        return {"estimate": None, "lower_95": None, "upper_95": None, "unit": "proportion", "status": "pending"}
    rng = random.Random(seed)
    samples = []
    for _ in range(draws):
        sample = [values[rng.randrange(len(values))] for _ in values]
        samples.append(sum(sample) / len(sample))
    samples.sort()
    return {
        "estimate": sum(values) / len(values),
        "lower_95": samples[int(draws * 0.025)],
        "upper_95": samples[int(draws * 0.975) - 1],
        "unit": "proportion; item-level bootstrap (document clustering requires source IDs in annotations)",
    }


def weighted_kappa(left: list[int], right: list[int]) -> float | None:
    if len(left) != len(right) or not left:
        return None
    observed = sum(1 - ((a - b) / 4) ** 2 for a, b in zip(left, right)) / len(left)
    expected = 0.0
    for a in range(1, 6):
        for b in range(1, 6):
            expected += (
                left.count(a) / len(left) * right.count(b) / len(right)
                * (1 - ((a - b) / 4) ** 2)
            )
    return (observed - expected) / (1 - expected) if expected < 1 else 1.0


def main() -> int:
    rows = read_rows()
    by_item: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        by_item[row["item_id"]].append(row)
    paired = [values[:2] for values in by_item.values() if len(values) >= 2]
    confidence_pairs = [
        (left["confidence"], right["confidence"])
        for left, right in paired
    ]
    report = {
        "schema": "ateval-m44-statistical-analysis-v1",
        "status": "complete" if rows else "pending_human_annotations",
        "annotation_count": len(rows),
        "reviewer_count": len({row.get("reviewer_id") for row in rows}),
        "items_with_two_or_more_reviewers": len(paired),
        "primary_endpoints": [
            "proportion of proposed revisions judged better than original",
            "proportion judged materially worse",
            "material scientific-meaning change rate",
            "unnecessary modification rate on adjudicated no-edit passages",
            "agreement between SCAR decisions and human necessity labels",
            "false acceptance and false rejection rates",
        ],
        "weighted_cohen_kappa_confidence": weighted_kappa(
            [pair[0] for pair in confidence_pairs],
            [pair[1] for pair in confidence_pairs],
        ),
        "krippendorff_alpha": "not calculated by stdlib-only pilot; calculate after multi-reviewer export with a validated implementation",
        "preference_proportions": {},
        "confidence_intervals": {},
        "document_clustered_bootstrap": "pending annotations with source-document grouping",
        "false_acceptance_rate": "pending adjudicated human labels",
        "false_rejection_rate": "pending adjudicated human labels",
        "limitations": [
            "No reviewer responses are generated by this script.",
            "The 30 comparison items are diagnostic development examples, not an independent test set.",
            "The current packet has no full paragraph context because frozen source artifacts do not contain it.",
        ],
    }
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "statistical_analysis.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
